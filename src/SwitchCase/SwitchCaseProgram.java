package SwitchCase;

public class SwitchCaseProgram {
	public static void main(String[] args) {
		int a = 40;
		int b = 10;
		switch(2) {
		case 1: int sum = a+b;
		System.out.println(sum);
		break;
		
		case 2: int sub = a-b;
		System.out.println(sub);
		break;
		
		case 3: int multi = a*b;
		System.out.println(multi);
		break;
		
		case 4: int div = a/b;
		System.out.println(div);
		break;
		
		default:
		}
			
			
	
	}

}
